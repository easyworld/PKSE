    const PersonalRecord &getPersonalInfo1RBY(uint16_t species, uint8_t form) noexcept
    {
        if (species == 0 || species > PERSONAL_MAX_SPECIES_1RBY)
        {
            return PERSONAL_RECORD_EMPTY;
        }
        const PersonalRecord &base = PERSONAL_1RBY[species];
        // Guarding formIndex == 0 matters: index 0 is a real row (species 0) and would
        // otherwise be returned as though it were a form.
        if (form == 0 || base.formIndex == 0 || form >= base.formCount)
        {
            return base;
        }
        const size_t formRowIndex = static_cast<size_t>(base.formIndex) + form - 1;
        if (formRowIndex >= PERSONAL_COUNT_1RBY)
        {
            return base;
        }
        return PERSONAL_1RBY[formRowIndex];
    }
