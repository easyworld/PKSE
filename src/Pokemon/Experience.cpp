    // Returns the total-EXP table for a growth rate. Out-of-range -> Medium Fast (0).
    static const uint32_t* getTable(uint8_t growth) noexcept
    {
        switch (growth)
        {
            case 0:  return kGrowth0;
            case 1:  return kGrowth1;
            case 2:  return kGrowth2;
            case 3:  return kGrowth3;
            case 4:  return kGrowth4;
            case 5:  return kGrowth5;
            default: return kGrowth0;
        }
    }

    uint8_t getLevelFromExp(uint32_t exp, uint8_t growthRate) noexcept
    {
        const uint32_t* table = getTable(growthRate);

        // Eagerly return 100 if exp is at/above the level-100 threshold.
        // Also guards the loop below from running off the end of the table.
        if (exp >= table[99])
            return 100;

        // Table is small; iterate upward from level 1 (mirrors PKHeX Experience.GetLevel).
        uint8_t tl = 1; // MinLevel
        while (tl < 100 && exp >= table[tl])
            ++tl;
        return tl;
    }

    uint32_t getExpForLevel(uint8_t level, uint8_t growthRate) noexcept
    {
        // Clamp to the valid level range [1,100].
        if (level < 1) level = 1;
        if (level > 100) level = 100;

        // Inverse of getLevelFromExp: same getTable() tables, indexed [level-1]
        // (table[0] = level-1 threshold, table[99] = level-100 threshold).
        const uint32_t* table = getTable(growthRate);
        return table[level - 1];
    }

